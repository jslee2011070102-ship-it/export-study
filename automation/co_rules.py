    정보 = 협정.get(협정키, {})
    종류 = 정보.get('문안')
    if 종류 is None:
        return None, False
    틀 = 영국_국문 if 국문 else 영국_영문
    번호 = 인증번호.strip() if 인증번호 else '...'
    원 = 원산지 if not 국문 else (원산지 if 원산지 != 'the Republic of Korea' else '대한민국')
    return 틀.format(인증번호=번호, 원산지=원), (종류 == '영국')
